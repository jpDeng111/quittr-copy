const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { createLessonService } = require('../lessons');
const { consumeSSE } = require('../public/event-stream');

test('authenticated lesson HTTP streams validated cards before done and caches the final deck', async (t) => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'quittr-lesson-stream-'));
  process.env.QUITTR_DATA_DIR = dir;
  process.env.DASHSCOPE_API_KEY = 'fixture-key';
  process.env.PUBLIC_ORIGIN = '';
  process.env.ALLOW_REGISTRATION = 'true';
  const fetchOriginal = global.fetch;
  const base = createLessonService({ readState: () => ({}), writeState() {} }).get().lesson;
  const text = JSON.stringify({ ...base, cards: base.cards.map((card) => ({ ...card, annotations: [{ text: card.body.slice(0, 4), style: 'underline' }] })) });
  const boundary = text.indexOf(',{"kind":"pattern"');
  const encode = new TextEncoder();
  let release, calls = 0;
  global.fetch = async (url, options) => {
    if (!String(url).endsWith('/chat/completions')) return fetchOriginal(url, options);
    calls++;
    const payload = JSON.parse(options.body);
    assert.equal(payload.stream, true);
    const stream = new ReadableStream({ async start(controller) {
      const delta = (content) => controller.enqueue(encode.encode(`data: ${JSON.stringify({ choices: [{ delta: { content } }] })}\n\n`));
      delta(text.slice(0, boundary));
      await new Promise((resolve) => { release = resolve; });
      delta(text.slice(boundary));
      controller.enqueue(encode.encode('data: {"choices":[{"delta":{},"finish_reason":"stop"}]}\n\ndata: [DONE]\n\n'));
      controller.close();
    } });
    return new Response(stream, { headers: { 'Content-Type': 'text/event-stream' } });
  };
  const { server, store } = require('../server');
  await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve));
  const origin = `http://127.0.0.1:${server.address().port}`;
  t.after(async () => { release?.(); global.fetch = fetchOriginal; await new Promise((resolve) => server.close(resolve)); store.close(); fs.rmSync(dir, { recursive: true }); });
  const registration = await fetch(origin + '/api/auth/register', { method: 'POST', headers: { Origin: origin, 'Content-Type': 'application/json' }, body: JSON.stringify({ email: 'lesson-fixture@example.com', password: 'local-test-password-123' }) });
  assert.equal(registration.status, 200);
  const cookie = registration.headers.get('set-cookie').split(';')[0];
  const headers = { Cookie: cookie, Origin: origin, 'Content-Type': 'application/json' };
  const unauthorized = await fetch(origin + '/api/lessons/daily', { method: 'POST', headers: { Origin: origin, 'Content-Type': 'application/json' }, body: '{"stream":true}' });
  assert.equal(unauthorized.status, 401);
  const invalid = await fetch(origin + '/api/lessons/daily', { method: 'POST', headers, body: '{"stream":true,"timeZone":"bad/zone"}' });
  assert.equal(invalid.status, 400);
  const response = await fetch(origin + '/api/lessons/daily', { method: 'POST', headers, body: '{"stream":true,"timeZone":"Asia/Shanghai"}' });
  assert.match(response.headers.get('content-type'), /text\/event-stream/);
  const events = [];
  let firstCard;
  const ready = new Promise((resolve) => { firstCard = resolve; });
  const consumed = consumeSSE(response.body, (event) => { events.push({ type: event.event, ...JSON.parse(event.data) }); if (event.event === 'card') firstCard(); });
  await ready;
  assert.equal(events.filter((event) => event.type === 'card').length, 1);
  assert.equal(events.some((event) => event.type === 'done'), false);
  release();
  await consumed;
  const done = events.at(-1);
  assert.equal(done.type, 'done');
  assert.equal(done.lesson.origin, 'ai');
  assert.equal(events.filter((event) => event.type === 'card').length, 5);
  const cached = await fetch(origin + '/api/lessons/daily', { method: 'POST', headers, body: '{"stream":true,"timeZone":"Asia/Shanghai"}' });
  const replay = [];
  await consumeSSE(cached.body, (event) => replay.push(event));
  assert.deepEqual(replay.map((event) => event.event), ['done']);
  assert.equal(calls, 1);
});
